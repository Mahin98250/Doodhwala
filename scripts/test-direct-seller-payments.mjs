import assert from "node:assert/strict";
import fs from "node:fs";

const read = (path) => fs.readFileSync(new URL("../" + path, import.meta.url), "utf8");
const payments = read("supabase/migrations/20261022150000_doodhwala_direct_seller_payments.sql");
const settingsRead = read("supabase/migrations/20261022151000_doodhwala_direct_upi_settings_read.sql");
const raceGuard = read("supabase/migrations/20261022152000_doodhwala_payment_choice_race_guard.sql");
const checkout = read("checkout.js");
const checkoutHtml = read("checkout.html");
const provider = read("provider.js");
const providerHtml = read("provider.html");
const orders = read("orders.js");

assert.match(payments, /create table if not exists public\.provider_payment_settings/i);
assert.match(payments, /revoke all on public\.provider_payment_settings from anon, authenticated/i);
assert.match(payments, /provider_save_direct_upi/);
assert.match(payments, /where owner_user_id = auth\.uid\(\)/i, "only the owning seller can configure UPI details");
assert.match(payments, /customer_check_provider_direct_upi/);
assert.match(payments, /where id=p_order_id and customer_id=auth\.uid\(\)/i, "customers can change payment choice only on their own order");
assert.match(payments, /where id=p_order_id and provider_owner_id=auth\.uid\(\)/i, "only the owning seller can confirm direct UPI receipt");
assert.match(payments, /cash_can_only_be_confirmed_after_delivery/);
assert.match(payments, /payment_confirmed_by=auth\.uid\(\)/);
assert.match(settingsRead, /where p\.owner_user_id=auth\.uid\(\)/i, "seller settings read must be owner-scoped");
assert.match(raceGuard, /set default 'selection_pending'/i, "new orders must not race into seller acceptance before payment choice is saved");
assert.match(raceGuard, /payment_method_selection_pending/);
assert.match(raceGuard, /if v_order\.payment_method=p_method then/i, "payment-choice RPC must be idempotent for retry after a lost response");
assert.match(checkout, /customer_check_provider_direct_upi/);
assert.match(checkout, /customer_set_order_payment_method/);
assert.match(checkout, /paymentMethod/);
assert.match(checkoutHtml, /value="direct_upi"/);
assert.match(checkoutHtml, /value="cod"/);
assert.match(providerHtml, /providerUpiId/);
assert.match(provider, /provider_save_direct_upi/);
assert.match(provider, /provider_confirm_direct_upi_payment/);
assert.match(provider, /provider_confirm_cod_collected/);
assert.match(provider, /bank settlement is not independently verified/);
assert.match(orders, /customer_get_order_direct_upi/);
assert.match(orders, /upi:\/\/pay\?/);
assert.match(orders, /Returning here does not prove payment/);
assert.doesNotMatch(checkout + provider + orders, /upi_pin|bank_password|card_cvv/i, "Doodhwala must never collect payment credentials");
console.log("Direct seller payment contracts passed: seller-scoped UPI, customer-owned orders, explicit COD, manual confirmation, and payment-choice race protection.");
